from __future__ import annotations

from collections.abc import Callable, Sequence
from typing import Protocol

from .models import FeedItem, FocusState, TelemetrySnapshot, WeatherSnapshot


class TelemetryService(Protocol):
    def latest(self) -> TelemetrySnapshot: ...
    def history(self) -> Sequence[TelemetrySnapshot]: ...
    def subscribe(self, callback: Callable[[TelemetrySnapshot], None]) -> Callable[[], None]: ...


class WeatherService(Protocol):
    def latest(self) -> WeatherSnapshot | None: ...
    def refresh_async(self, callback: Callable[[WeatherSnapshot], None]) -> None: ...


class FeedService(Protocol):
    def latest(self) -> Sequence[FeedItem]: ...
    def refresh_async(self, callback: Callable[[Sequence[FeedItem]], None]) -> None: ...


class FocusService(Protocol):
    def state(self) -> FocusState: ...
    def start(self) -> FocusState: ...
    def pause(self) -> FocusState: ...
    def reset(self) -> FocusState: ...
